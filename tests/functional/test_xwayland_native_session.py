"""Integration test: Satellite must report PHYSICAL modes, not Wayland logical ones.

A 2560x1440 headless output at scale 1.25 has logical size 2048x1152.
This test proves the session-wide DISPLAY / XRandR route actually exposes
2560x1440. It catches regressions that an external game-launcher test misses.
"""

import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
import time
import unittest

from harness import Session, tool


class NativeXwaylandSession(unittest.TestCase):
    def setUp(self):
        if not shutil.which("xwayland-satellite"):
            self.skipTest("xwayland-satellite (>= 0.7) not available")
        if not shutil.which("xrandr"):
            self.skipTest("xrandr not available")
        self.tmp = tempfile.TemporaryDirectory(prefix="vela-native-display-")
        self.display_file = Path(self.tmp.name) / "session-display"
        self.auth_file = Path(self.tmp.name) / "session-auth"
        self.vela = Session(
            scale=1.25, size="2560x1440@60",
            env={"VELA_XWAYLAND_BACKEND": "native",
                 "VELA_NATIVE_TEST_DISPLAY_FILE": str(self.display_file),
                 "VELA_NATIVE_TEST_AUTH_FILE": str(self.auth_file)},
            startup=('printf %s "$DISPLAY" > "$VELA_NATIVE_TEST_DISPLAY_FILE"; '
                     'printf %s "$XAUTHORITY" > "$VELA_NATIVE_TEST_AUTH_FILE"'),
        )
        self.vela.start()

    def tearDown(self):
        if hasattr(self, "vela"):
            self.vela.stop()
        if hasattr(self, "tmp"):
            self.tmp.cleanup()

    def x11_env(self, display):
        # XAUTHORITY is generated by the compositor after the test harness
        # starts: Python's inherited environment cannot know the cookie.
        deadline = time.monotonic() + 8
        while time.monotonic() < deadline:
            if self.auth_file.exists() and self.auth_file.stat().st_size:
                return dict(self.vela.client_env, DISPLAY=display,
                            XAUTHORITY=self.auth_file.read_text())
            time.sleep(0.05)
        self.fail("Satellite session did not export XAUTHORITY")

    def test_ewmh_maximize_bridge(self):
        # Satellite main currently handles _NET_WM_STATE_FULLSCREEN but not
        # the paired MAXIMIZED_HORZ/MAXIMIZED_VERT request used by Steam CSD.
        # Keep the reproduction in-tree, but do not fail all GPU tests until
        # upstream Satellite adds support (issues #269 and #460). Set this
        # opt-in on a patched Satellite build to verify the eventual fix.
        if os.environ.get("VELA_ASSERT_SATELLITE_MAXIMIZE") != "1":
            self.skipTest("Blocked upstream: Satellite does not forward EWMH maximize (#269)")
        if not os.path.exists(tool("vela-x11")):
            self.skipTest("vela-x11 test client requires XCB build dependency")
        display = self.vela.wait_for_log(
            "Native-resolution X11 Satellite listening on DISPLAY=",
            lambda line: line.split("DISPLAY=")[1].split()[0],
        )
        env = self.x11_env(display)
        xid_path = Path(self.tmp.name) / "xid"
        before = {w["id"] for w in self.vela.state().windows}
        self.vela.clients.append(subprocess.Popen(
            [tool("vela-x11"), "--id-file", str(xid_path), "640", "480"], env=env))
        self.vela.wait_for(
            lambda state: bool({w["id"] for w in state.windows} - before),
            timeout=15, what="Satellite toplevel mapped")
        window = next(iter({w["id"] for w in self.vela.state().windows} - before))
        self.vela.wait_still(window)
        deadline = time.monotonic() + 8
        while not xid_path.exists() and time.monotonic() < deadline:
            time.sleep(0.1)
        self.assertTrue(xid_path.exists(), "native X11 client did not publish its XID")
        subprocess.run(
            [tool("vela-x11"), "--state", xid_path.read_text().strip(), "maximize", "on"],
            env=env, check=True, timeout=8,
        )
        self.vela.wait_for(
            lambda state: state.window(window)["maximized"],
            timeout=8, what="paired EWMH maximize delivered through Satellite to XDG")

    def test_icccm_minimize_bridge(self):
        # Steam's minimize button can use XIconifyWindow: ICCCM
        # WM_CHANGE_STATE/IconicState. The host compositor receives XDG
        # minimize requests, not raw X11 messages; Satellite must bridge them.
        if os.environ.get("VELA_ASSERT_SATELLITE_MINIMIZE") != "1":
            self.skipTest("Blocked upstream: Satellite lacks ICCCM WM_CHANGE_STATE forwarding")
        if not os.path.exists(tool("vela-x11")):
            self.skipTest("vela-x11 test client requires XCB build dependency")
        display = self.vela.wait_for_log(
            "Native-resolution X11 Satellite listening on DISPLAY=",
            lambda line: line.split("DISPLAY=")[1].split()[0],
        )
        env = self.x11_env(display)
        xid_path = Path(self.tmp.name) / "minimize-xid"
        before = {w["id"] for w in self.vela.state().windows}
        self.vela.clients.append(subprocess.Popen(
            [tool("vela-x11"), "--id-file", str(xid_path), "640", "480"], env=env))
        self.vela.wait_for(
            lambda state: bool({w["id"] for w in state.windows} - before),
            timeout=15, what="minimize target mapped via Satellite")
        window = next(iter({w["id"] for w in self.vela.state().windows} - before))
        self.vela.wait_still(window)
        deadline = time.monotonic() + 8
        while not xid_path.exists() and time.monotonic() < deadline:
            time.sleep(0.1)
        self.assertTrue(xid_path.exists())
        subprocess.run(
            [tool("vela-x11"), "--iconify", xid_path.read_text().strip()],
            env=env, check=True, timeout=8,
        )
        self.vela.wait_for(
            lambda state: state.window(window)["minimized"],
            timeout=8, what="ICCCM IconicState delivered through Satellite to XDG")

    def test_satellite_x11_requires_private_xauthority(self):
        """Reject connections via the abstract X11 socket without the cookie."""
        display = self.vela.wait_for_log(
            "Native-resolution X11 Satellite listening on DISPLAY=",
            lambda line: line.split("DISPLAY=")[1].split()[0],
        )
        deadline = time.monotonic() + 8
        while not self.auth_file.exists() and time.monotonic() < deadline:
            time.sleep(0.1)
        self.assertTrue(self.auth_file.exists(), "session startup missed XAUTHORITY")
        auth_path = Path(self.auth_file.read_text())
        self.assertTrue(auth_path.is_file(), "Satellite authorization file missing")
        self.assertEqual(auth_path.stat().st_mode & 0o777, 0o600)
        self.assertGreaterEqual(auth_path.stat().st_size, 32)
        self.assertIn(b"MIT-MAGIC-COOKIE-1", auth_path.read_bytes())

        env = self.x11_env(display)
        env["XAUTHORITY"] = str(Path(self.tmp.name) / "invalid-auth")
        denied = subprocess.run(["xrandr", "--query"], env=env, capture_output=True,
                                text=True, timeout=8)
        self.assertNotEqual(denied.returncode, 0,
                            "Satellite accepted an X11 client without a valid cookie")

    def test_satellite_xrandr_reports_native_mode(self):
        display = self.vela.wait_for_log(
            "Native-resolution X11 Satellite listening on DISPLAY=",
            lambda line: line.split("DISPLAY=")[1].split()[0],
        )
        self.assertRegex(display, r"^:\d+$")
        # This verifies the display apps inherit from Vela, not an explicitly
        # overridden per-game DISPLAY.
        deadline = time.monotonic() + 8
        while not self.display_file.exists() and time.monotonic() < deadline:
            time.sleep(0.1)
        self.assertTrue(self.display_file.exists(), "session startup did not run")
        self.assertEqual(self.display_file.read_text(), display)
        env = self.x11_env(display)
        deadline = time.monotonic() + 15
        output = ""
        while time.monotonic() < deadline:
            query = subprocess.run(["xrandr", "--query"], env=env,
                                   text=True, stdout=subprocess.PIPE,
                                   stderr=subprocess.PIPE, timeout=5)
            if query.returncode == 0 and "connected" in query.stdout:
                output = query.stdout
                break
            time.sleep(0.15)
        self.assertTrue(output, "Satellite XRandR server did not become ready")
        self.assertRegex(output, r"(?m)^\s+2560x1440\s")
        # The logical size must not be advertised as the active physical mode.
        self.assertNotRegex(output, r"(?m)^\S+ connected 2048x1152")


class NativeXwaylandMixedScaleInput(unittest.TestCase):
    """Guard the 125%/100% cross-output X11 pointer coordinate conversion."""

    def setUp(self):
        # Kept opt-in until the Satellite viewport/input-region patches have
        # been reviewed and a patched backend is available on GPU runners.
        if os.environ.get("VELA_ASSERT_SATELLITE_MIXED_INPUT") != "1":
            self.skipTest("Satellite mixed-scale input-region fix not yet integrated (upstream #452)")
        if not shutil.which("xwayland-satellite") or not os.path.exists(tool("vela-x11")):
            self.skipTest("Satellite and vela-x11 must both be available")
        self.tmp = tempfile.TemporaryDirectory(prefix="vela-x11-input-")
        self.auth_file = Path(self.tmp.name) / "session-auth"
        self.vela = Session(scale="HEADLESS-1=1.25,HEADLESS-2=1",
                            size="2560x1440@60",
                            env={"VELA_XWAYLAND_BACKEND": "native",
                                 "VELA_NATIVE_TEST_AUTH_FILE": str(self.auth_file)},
                            startup='printf %s "$XAUTHORITY" > "$VELA_NATIVE_TEST_AUTH_FILE"')
        self.vela.start()
        self.vela.command("test-output add 1920x1080")
        self.vela.wait_for(lambda s: len(s["outputs"]) == 2,
                           what="mixed-scale output layout")
        self.vela.randr("--output", "HEADLESS-2", "--scale", "1",
                        "--pos", "2048,0")
        self.vela.wait_for(
            lambda s: any(o["name"] == "HEADLESS-2" and o["scale"] == 1
                          for o in s["outputs"]),
            what="second 100% output configured")

    def tearDown(self):
        if hasattr(self, "vela"):
            self.vela.stop()
        if hasattr(self, "tmp"):
            self.tmp.cleanup()

    def test_pointer_delta_matches_output_scale_after_move(self):
        display = self.vela.wait_for_log(
            "Native-resolution X11 Satellite listening on DISPLAY=",
            lambda line: line.split("DISPLAY=")[1].split()[0],
        )
        deadline = time.monotonic() + 8
        while (not self.auth_file.exists() or not self.auth_file.stat().st_size) and time.monotonic() < deadline:
            time.sleep(0.05)
        self.assertTrue(self.auth_file.exists() and self.auth_file.stat().st_size)
        env = dict(self.vela.client_env, DISPLAY=display, XAUTHORITY=self.auth_file.read_text())
        xid_file = Path(self.tmp.name) / "pointer-window"
        before = {w["id"] for w in self.vela.state().windows}
        self.vela.clients.append(subprocess.Popen(
            [tool("vela-x11"), "--id-file", str(xid_file), "640", "480"],
            env=env))
        self.vela.wait_for(
            lambda s: bool({w["id"] for w in s.windows} - before),
            what="native X11 input probe mapped")
        window = next(iter({w["id"] for w in self.vela.state().windows} - before))
        self.vela.wait_still(window)
        deadline = time.monotonic() + 8
        while not xid_file.exists() and time.monotonic() < deadline:
            time.sleep(0.1)
        self.assertTrue(xid_file.exists())
        xid = xid_file.read_text().strip()

        def pointer_x(x, y):
            self.vela.input("move", x, y, "sleep", "100")
            result = subprocess.run([tool("vela-x11"), "--pointer", xid],
                                    env=env, capture_output=True,
                                    text=True, check=True, timeout=5)
            rel_x, _rel_y, same_screen = map(int, result.stdout.split())
            self.assertEqual(same_screen, 1)
            return rel_x

        def assert_scaled_delta(scale):
            w = self.vela.state().window(window)
            x, y = w["x"] + w["w"] // 2, w["y"] + w["h"] // 2
            left, right = pointer_x(x - 32, y), pointer_x(x + 32, y)
            self.assertAlmostEqual(right - left, 64 * scale, delta=3)

        assert_scaled_delta(1.25)
        w = self.vela.state().window(window)
        secondary = next(o for o in self.vela.state()["outputs"]
                         if o["name"] == "HEADLESS-2")
        grab_x, grab_y = w["x"] + 40, w["y"] + 45
        tx, ty = secondary["x"] + 200, secondary["y"] + 180
        self.vela.input("move", grab_x, grab_y,
                        "keydown", "super", "down", "sleep", "50",
                        "move", (grab_x + tx) // 2, (grab_y + ty) // 2,
                        "sleep", "50", "move", tx, ty, "sleep", "100",
                        "up", "keyup", "super")
        self.vela.wait_for(
            lambda s: s.window(window)["output"] == "HEADLESS-2",
            what="X11 pointer probe moved to 100% output")
        self.vela.wait_still(window)
        assert_scaled_delta(1.0)
